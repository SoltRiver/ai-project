def get_japanese_name(symbol: str, english_name: str = "") -> str:
    """
    銘柄コードから日本語名を取得

    Args:
        symbol: 銘柄コード
        english_name: 英語名（フォールバック用）

    Returns:
        日本語名。見つからない場合は英語名またはコードを返す。
    """
    japanese_name = STOCK_NAME_MAP.get(symbol)
    if japanese_name:
        return japanese_name
    normalized = symbol.replace(".T", "")
    japanese_name = STOCK_NAME_MAP.get(normalized)
    if japanese_name:
        return japanese_name
    return english_name if english_name else symbol
